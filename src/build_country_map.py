"""Regenerate countries.py: which currency each country on the map uses.

The world map colours every country by how its currency moved, so it needs a
country -> currency table. That table is not something to type by hand, and it
is not something to download every time the dashboard runs either, so it is
generated once by this script and committed as countries.py.

Source: the ISO 3166 / ISO 4217 table published by the Frictionless Data
"country-codes" dataset, which pairs each country's alpha-3 code with the
currency it issues. Run this again if a country changes currency:

    python src/build_country_map.py
"""

import json
import pathlib
import urllib.request

SOURCE = (
    "https://raw.githubusercontent.com/datasets/country-codes/main/"
    "data/country-codes.csv"
)
HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE / "countries.py"


def rows():
    import csv
    import io

    request = urllib.request.Request(SOURCE, headers={"User-Agent": "currency-dashboard"})
    with urllib.request.urlopen(request, timeout=120) as response:
        text = response.read().decode("utf-8")
    return list(csv.DictReader(io.StringIO(text)))


def known_currencies():
    """The currency codes this project actually has rates for."""
    snapshots = sorted(HERE.glob("data/currencies_*.json"))
    latest = json.loads(snapshots[-1].read_text())
    return {c["iso_code"] for c in latest if c.get("type", "currency") == "currency"}


def build():
    ours = known_currencies()
    currency_of, name_of = {}, {}
    for row in rows():
        alpha3 = (row.get("ISO3166-1-Alpha-3") or "").strip()
        alpha2 = (row.get("ISO3166-1-Alpha-2") or "").strip()
        listed = [c.strip() for c in (row.get("ISO4217-currency_alphabetic_code") or "").split(",") if c.strip()]
        if not alpha3 or not listed:
            continue
        usable = [c for c in listed if c in ours]
        if not usable:
            continue
        # a few countries list more than one currency (Bhutan takes the Indian
        # rupee alongside its own ngultrum). Prefer the one the country issues
        # itself, which is the code starting with its own two letters.
        own = [c for c in usable if c[:2] == alpha2]
        currency_of[alpha3] = (own or usable)[0]
        name_of[alpha3] = (row.get("official_name_en") or alpha3).strip()
    return currency_of, name_of


def render(currency_of, name_of):
    lines = [
        '"""Which currency each country uses, and its English name.',
        "",
        "Generated by build_country_map.py from the ISO 3166 / ISO 4217 table.",
        "Do not edit by hand: run that script instead.",
        '"""',
        "",
        "COUNTRY_CURRENCY = {",
    ]
    for code in sorted(currency_of):
        lines.append(f'    "{code}": "{currency_of[code]}",')
    lines += ["}", "", "COUNTRY_NAMES = {"]
    for code in sorted(name_of):
        lines.append(f'    "{code}": "{name_of[code]}",')
    lines += ["}", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    currency_of, name_of = build()
    OUT.write_text(render(currency_of, name_of))
    print(f"wrote {OUT.name}: {len(currency_of)} countries, "
          f"{len(set(currency_of.values()))} currencies")
